#!/bin/bash
#
# Event display for the ALLEGRO detector for FCC-ee
# author: Giovanni Marchiori (giovanni.marchiori@cern.ch)
#
# geometry_code_version.sh: write to stdout a header defining
# GEOMETRY_CODE_VERSION, a hash of the code that decides which volumes of the
# G4 geometry are drawn (and so which ones are kept in the geometry cache): the
# functions listed below of src/EventDisplay.cpp and all of
# src/GeometryCache.cpp. The geometry caches written by a different version of
# that code are rebuilt.
#
# usage: geometry_code_version.sh <src dir>
#
# When a function that changes which volumes are drawn is added (or renamed),
# add it to the list. The comment lines and blank lines are not hashed.
#

FUNCTIONS=(
  # building the geometry
  buildG4Geometry buildFullDetector buildCalorimeters
  findSubDetector subDetectorList setVolumeStyle findElementBeginningWith
  # the subdetectors
  addSimpleElement addVertex addDCH addWrapper addECalB addECalEC
  addHCalB addHCalEC addMuonB addMuonEC
  # the content shown
  showEnvelopeContent showVertexBarrelLayers showECalBathCells
  showECalEndcapContent showECalBarrelContent showMuonLayers
  # the projections, and the views from which the cache is written
  projectGeometryRhoPhi projectGeometryRhoZ writeGeometryCache
)

SRC=${1:-src}

# the definition of a function: from its first line, starting at column 0,
# to the first closing brace at column 0
extract() {
  awk -v name="$1" '
    !inside && /^[A-Za-z]/ && $0 ~ "(^|[ *&:])" name "\\(" { inside = 1; n++ }
    inside { print }
    inside && /^}/ { inside = 0 }
    END { if (n != 1) { print "geometry_code_version.sh: " n+0 " definitions of " name " in EventDisplay.cpp: update the list" > "/dev/stderr"; exit 1 } }
  ' "$SRC/EventDisplay.cpp"
}

code=$(
  for f in "${FUNCTIONS[@]}"; do
    extract "$f" || exit 1
  done
  cat "$SRC/GeometryCache.cpp"
) || exit 1

# (cksum is available everywhere, also on macOS)
hash=$(printf '%s\n' "$code" | grep -vE '^[[:space:]]*(//.*)?$' | cksum | cut -d' ' -f1)

echo "// generated by scripts/geometry_code_version.sh: do not edit"
echo "#define GEOMETRY_CODE_VERSION \"$hash\""
